export function formatTaskRequestDuration(milliseconds: number) {
  if (milliseconds < 1000) {
    return `${milliseconds} ms`
  }
  return `${(milliseconds / 1000).toFixed(2)} s`
}

export function formatTaskRequestBytes(bytes: number) {
  if (bytes < 1024) {
    return `${bytes} B`
  }
  if (bytes < 1024 * 1024) {
    return `${(bytes / 1024).toFixed(1)} KB`
  }
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`
}
